"""Reproducible SYNTHETIC e-commerce datasets with controllable drift.

All data produced here is synthetic. Reference and current datasets are drawn
from independent random streams (``SeedSequence.spawn``) so that the
current data never reuses reference samples.
"""

from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np
import pandas as pd

SYNTHETIC_LABEL = "SYNTHETIC DATA - generated by DriftGuard AI for demonstration only"


@dataclass(frozen=True)
class Scenario:
    key: str
    label: str
    description: str
    expected_drift: tuple[str, ...] = ()
    expected_quality_checks: tuple[str, ...] = ()


SCENARIOS: dict[str, Scenario] = {
    s.key: s
    for s in [
        Scenario(
            "stable",
            "Stable (no intentional drift)",
            "Current data is drawn from exactly the same distributions as the reference, with a different random seed.",
        ),
        Scenario(
            "mean_shift",
            "Mean shift",
            "Customer age shifts up by about 6 years and annual income rises about 25%.",
            ("age", "annual_income"),
        ),
        Scenario(
            "variance_shift",
            "Variance shift",
            "Session duration and discount rate keep the same mean but become much more spread out.",
            ("session_minutes", "discount_rate"),
        ),
        Scenario(
            "category_shift",
            "Categorical proportion shift",
            "Device mix moves toward mobile and UPI overtakes card as the top payment method.",
            ("device_type", "payment_method"),
        ),
        Scenario(
            "new_category",
            "New categories appear",
            "New payment method 'bnpl' (about 12%) and new device 'smart_tv' (about 6%) appear in current data.",
            ("device_type", "payment_method"),
            ("unseen_categories",),
        ),
        Scenario(
            "missing_increase",
            "Increased missing values",
            "Missing values rise sharply in income, region and session duration; observed distributions are unchanged.",
            (),
            ("missing_increase",),
        ),
        Scenario(
            "schema_change",
            "Schema change",
            "'session_minutes' is dropped, 'referral_source' is added, and 'account_tenure_months' arrives as text.",
            (),
            ("missing_column", "new_column", "type_mismatch"),
        ),
        Scenario(
            "combined",
            "Combined production incident",
            "Mean shift, categorical shift, a new category and increased missing values at the same time.",
            ("age", "annual_income", "device_type", "payment_method"),
            ("missing_increase", "unseen_categories"),
        ),
    ]
}


@dataclass
class SyntheticDataset:
    scenario: Scenario
    reference: pd.DataFrame
    current: pd.DataFrame
    seed: int
    notes: list[str] = field(default_factory=lambda: [SYNTHETIC_LABEL])


def _generate(
    rng: np.random.Generator,
    n: int,
    *,
    age_mean: float = 38.0,
    income_multiplier: float = 1.0,
    session_shape: float = 2.0,
    session_scale: float = 6.0,
    discount_ab: tuple[float, float] = (2.0, 8.0),
    devices: dict[str, float] | None = None,
    payments: dict[str, float] | None = None,
    missing: dict[str, float] | None = None,
    id_offset: int = 0,
) -> pd.DataFrame:
    devices = devices or {"mobile": 0.55, "desktop": 0.35, "tablet": 0.10}
    payments = payments or {"card": 0.45, "upi": 0.30, "wallet": 0.15, "cod": 0.10}
    regions = {"North": 0.25, "South": 0.25, "East": 0.20, "West": 0.20, "Central": 0.10}
    missing = missing if missing is not None else {"annual_income": 0.02, "session_minutes": 0.01}

    def choice(options: dict[str, float]) -> np.ndarray:
        keys = list(options)
        probs = np.array([options[k] for k in keys], dtype=float)
        return rng.choice(keys, size=n, p=probs / probs.sum())

    df = pd.DataFrame(
        {
            "customer_id": [f"CUST-{id_offset + i:07d}" for i in range(n)],
            "age": np.clip(np.round(rng.normal(age_mean, 11.0, n)), 18, 80).astype(int),
            "annual_income": np.round(rng.lognormal(np.log(55_000 * income_multiplier), 0.45, n), -2),
            "session_minutes": np.round(rng.gamma(session_shape, session_scale, n), 2),
            "items_in_cart": rng.poisson(3.0, n),
            "account_tenure_months": rng.integers(0, 121, n),
            "discount_rate": np.round(rng.beta(*discount_ab, n), 4),
            "device_type": choice(devices),
            "region": choice(regions),
            "payment_method": choice(payments),
            "is_premium": rng.random(n) < 0.2,
        }
    )
    for col, rate in missing.items():
        if col in df and rate > 0:
            mask = rng.random(n) < rate
            df[col] = df[col].mask(mask)
    return df


def generate_scenario(
    scenario: str = "stable", n_reference: int = 5000, n_current: int = 3000, seed: int = 42
) -> SyntheticDataset:
    if scenario not in SCENARIOS:
        raise ValueError(f"Unknown scenario '{scenario}'. Choose from: {', '.join(SCENARIOS)}.")
    if n_reference < 50 or n_current < 50:
        raise ValueError("Synthetic datasets need at least 50 rows each.")
    if n_reference > 200_000 or n_current > 200_000:
        raise ValueError("Synthetic datasets are limited to 200,000 rows each.")

    ref_seq, cur_seq = np.random.SeedSequence(seed).spawn(2)
    reference = _generate(np.random.default_rng(ref_seq), n_reference)
    cur_rng = np.random.default_rng(cur_seq)
    kwargs: dict = {"id_offset": n_reference}

    if scenario in ("mean_shift", "combined"):
        kwargs |= {"age_mean": 44.0, "income_multiplier": 1.25}
    if scenario == "variance_shift":
        # Same means as reference (gamma 2*6 = 0.8*15 = 12; beta 2/10 = 0.6/3 = 0.2).
        kwargs |= {"session_shape": 0.8, "session_scale": 15.0, "discount_ab": (0.6, 2.4)}
    if scenario in ("category_shift", "combined"):
        kwargs |= {
            "devices": {"mobile": 0.75, "desktop": 0.20, "tablet": 0.05},
            "payments": {"card": 0.30, "upi": 0.50, "wallet": 0.12, "cod": 0.08},
        }
    if scenario == "new_category":
        kwargs |= {
            "devices": {"mobile": 0.52, "desktop": 0.33, "tablet": 0.09, "smart_tv": 0.06},
            "payments": {"card": 0.40, "upi": 0.26, "wallet": 0.13, "cod": 0.09, "bnpl": 0.12},
        }
    if scenario == "combined":
        kwargs["payments"] = {"card": 0.28, "upi": 0.45, "wallet": 0.10, "cod": 0.07, "bnpl": 0.10}
    if scenario in ("missing_increase", "combined"):
        kwargs["missing"] = {"annual_income": 0.20, "session_minutes": 0.10, "region": 0.15}

    current = _generate(cur_rng, n_current, **kwargs)

    if scenario == "schema_change":
        current = current.drop(columns=["session_minutes"])
        current["referral_source"] = cur_rng.choice(
            ["organic", "ads", "social", "email"], size=n_current, p=[0.4, 0.3, 0.2, 0.1]
        )
        current["account_tenure_months"] = current["account_tenure_months"].map(lambda m: f"{m} months")

    return SyntheticDataset(SCENARIOS[scenario], reference, current, seed)
